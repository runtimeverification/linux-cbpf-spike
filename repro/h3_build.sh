#!/bin/sh
# Build the H3 differential harness. Extracts the kernel functions VERBATIM
# from ~/linux-cbpf (read-only) into h3_kernel_extract.h, then compiles.
set -eu
T="$HOME/linux-cbpf"
cd "$(dirname "$0")"
{
  echo "/* GENERATED by h3_build.sh from $T @ $(git -C "$T" describe --always --long) */"
  echo "/* Verbatim kernel functions. Do not edit. */"
  echo "/* --- include/linux/filter.h: bpf_anc_helper --- */"
  awk '/^static inline u16 bpf_anc_helper/,/^}/' "$T/include/linux/filter.h"
  echo "/* --- net/core/filter.c: check_load_and_stores, chk_code_allowed, bpf_check_classic --- */"
  awk '/^static int check_load_and_stores/,/^}/' "$T/net/core/filter.c"
  awk '/^static bool chk_code_allowed/,/^}/'     "$T/net/core/filter.c"
  awk '/^static int bpf_check_classic/,/^}/'     "$T/net/core/filter.c"
  echo "/* --- kernel/seccomp.c: seccomp_check_filter, seccomp_uprobe_exception, seccomp_is_const_allow --- */"
  awk '/^static int seccomp_check_filter/,/^}/'      "$T/kernel/seccomp.c"
  awk '/^static bool seccomp_uprobe_exception/,/^}/' "$T/kernel/seccomp.c"
  awk '/^static bool seccomp_is_const_allow/,/^}/'   "$T/kernel/seccomp.c"
} > h3_kernel_extract.h
gcc -O2 -Wall -Wno-cpp -D__user= -I stub -I "$T/include/uapi" -I "$T/arch/x86/include/uapi" \
    -o h3_const_allow_fuzz h3_const_allow_fuzz.c
echo "built h3_const_allow_fuzz ($(wc -l < h3_kernel_extract.h) extracted lines, sha256 $(sha256sum h3_kernel_extract.h | cut -c1-16))"
