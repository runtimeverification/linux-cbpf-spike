#!/bin/sh
# Build the H4 harness. Reuses the verbatim kernel extract (h3_kernel_extract.h,
# regenerated here from ~/linux-cbpf, read-only).
set -eu
T="$HOME/linux-cbpf"
cd "$(dirname "$0")"
{
  echo "/* GENERATED by h4_build.sh from $T @ $(git -C "$T" describe --always --long) */"
  echo "/* Verbatim kernel functions. Do not edit. */"
  awk '/^static inline u16 bpf_anc_helper/,/^}/' "$T/include/linux/filter.h"
  awk '/^static int check_load_and_stores/,/^}/' "$T/net/core/filter.c"
  awk '/^static bool chk_code_allowed/,/^}/'     "$T/net/core/filter.c"
  awk '/^static int bpf_check_classic/,/^}/'     "$T/net/core/filter.c"
  awk '/^static int seccomp_check_filter/,/^}/'      "$T/kernel/seccomp.c"
  awk '/^static bool seccomp_uprobe_exception/,/^}/' "$T/kernel/seccomp.c"
  awk '/^static bool seccomp_is_const_allow/,/^}/'   "$T/kernel/seccomp.c"
} > h3_kernel_extract.h
gcc -O2 -Wall -Wno-cpp -D__user= -I stub -I "$T/include/uapi" -I "$T/arch/x86/include/uapi" \
    -o h4_mem_init_fuzz h4_mem_init_fuzz.c
echo "built h4_mem_init_fuzz (extract sha256 $(sha256sum h3_kernel_extract.h | cut -c1-16))"
